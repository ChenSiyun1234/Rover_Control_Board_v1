def write_csv(path, rows):
    """Write full-precision, consistently ordered experiment records."""
    with path.open("w", newline="", encoding="utf-8") as output:
        writer = csv.DictWriter(output, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def markdown_table(rows, fields):
    """Format reviewed rows with explicit unit-bearing column labels."""

    def display(value):
        if value is None:
            return "n/a"
        if isinstance(value, bool):
            return "yes" if value else "no"
        if isinstance(value, float):
            return f"{value:.3f}"
        return str(value)

    header = "| " + " | ".join(label for _, label in fields) + " |\n"
    divider = "|" + "---|" * len(fields) + "\n"
    body = "\n".join(
        "| " + " | ".join(display(row[key]) for key, _ in fields) + " |" for row in rows
    )
    return header + divider + body + "\n"


def delay_text(value):
    """Label missing true-threshold crossings without inventing zero delay."""
    return "n/a" if value is None else f"{value:.1f} ms"


