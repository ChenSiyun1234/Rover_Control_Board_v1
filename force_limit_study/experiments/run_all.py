def main():
    """Run the fixed experiment matrix and regenerate every result artifact."""
    started = time.perf_counter()
    output = ROOT / "results"
    output.mkdir(exist_ok=True)
    rows = {
        name: []
        for name in (
            "e1",
            "e2",
            "e2_nominal",
            "e2_previous",
            "e3",
            "e4",
            "e4_nominal",
            "e5",
        )
    }
    jam_traces = {}
    plant_traces = {}
    for adc in ADC_ORDER:
        for speed in (25, 50, 100, 200):
            if speed == 100:
                metrics, trace, plant_trace = jam_case(adc=adc, speed=speed, include_plant_trace=True)
                jam_traces[adc] = metrics, trace
                plant_traces[adc] = metrics, plant_trace
            else:
                metrics, trace = jam_case(adc=adc, speed=speed)
            rows["e1"].append(metrics)
        print(f"E1: {adc}", flush=True)
    for stiffness in (200, 50, 20, 5):
        for adc in ("HX711_80", "ADS1220_1000"):
            for speed in (50, 100):
                rows["e2"].append(
                    jam_case(
                        adc=adc, speed=speed, stiffness=stiffness, acceleration=50
                    )[0]
                )
        for acceleration in (500, 50):
            rows["e2_nominal"].append(
                nominal_case(stiffness=stiffness, acceleration=acceleration)[0]
            )
    for stiffness in (200, 50, 20, 5):
        rows["e2_previous"].append(
            nominal_case(
                stiffness=stiffness, gains={"velocity_kp": 0.035, "velocity_ki": 0.8}
            )[0]
        )
    print("E2 complete", flush=True)
    for jam_mm in (50, 150, 250):
        for envelope in (True, False):
            rows["e3"].append(jam_case(jam_mm=jam_mm, envelope=envelope)[0])
    print("E3 complete", flush=True)
    for cutoff in CUTOFFS:
        aggregate, runs = filter_cases(cutoff)
        rows["e4"].append(aggregate)
        rows["e4_nominal"].extend(runs)
        print(f"E4: {cutoff} Hz, {len(runs)} seeds", flush=True)
    nominal_metrics, nominal_trace = nominal_case()
    rows["e5"].append(nominal_metrics)
    for name, records in rows.items():
        write_csv(output / f"{name}.csv", records)
    write_csv(output / "velocity.csv", [velocity_check()])
    # Persist the plotted traces so a figure can be independently inspected.
    trace_fields = (
        "time_s",
        "carriage_mm",
        "server_mm",
        "true_force_N",
        "measured_force_N",
        "state",
        "current_command_A",
        "drive_enable",
        "measured_velocity_mm_s",
        "reference_velocity_mm_s",
        "raw_force_N",
        "limit_N",
        "server_est_mm",
        "true_velocity_mm_s",
        "driver_current_A",
        "rack_force_N",
    )
    with (output / "nominal_trace.csv").open("w", newline="") as destination:
        writer = csv.writer(destination)
        writer.writerow(trace_fields)
        writer.writerows(nominal_trace)
    for adc, (metrics, trace) in jam_traces.items():
        selected = ((trace[:, TraceColumn.TIME_S] - metrics["contact_s"]) >= -0.02) & (
            (trace[:, TraceColumn.TIME_S] - metrics["contact_s"]) <= 0.65
        )
        with (output / f"jam_{adc}.csv").open("w", newline="") as destination:
            writer = csv.writer(destination)
            writer.writerow(trace_fields)
            writer.writerows(trace[selected])
    for adc, (metrics, trace) in plant_traces.items():
        selected = ((trace[:, 0] - metrics["contact_s"]) >= -0.02) & ((trace[:, 0] - metrics["contact_s"]) <= 0.65)
        with (output / f"jam_{adc}_plant.csv").open("w", newline="") as destination:
            writer = csv.writer(destination)
            writer.writerow(("time_s", "rack_force_N"))
            writer.writerows(trace[selected])
    make_figures(output, rows, nominal_trace, jam_traces, ADC_ORDER)
    write_report(rows)
    print(
        f"E1-E5 complete: {sum(len(records) for records in rows.values())} table rows; "
        f"results/*.csv, results/*.png, docs/RESULTS.md ({time.perf_counter() - started:.2f} s)"
    )


if __name__ == "__main__":
    main()
