"""Extract the FSR channel from KiCad connectivity and native SPICE values."""
import argparse
import os
from pathlib import Path
import re

from board.pin_map import parse, children

REVISIONS = {"now": "5db1aab", "prev": "e9beafa"}


def spice_value(value):
    """Decode SPICE suffixes (M is milli; Meg is mega)."""
    match = re.fullmatch(r"([\d.eE+-]+)([a-zA-Z]*)", value)
    number, suffix = match.groups()
    scales = {"": 1, "t": 1e12, "g": 1e9, "meg": 1e6, "k": 1e3,
              "m": 1e-3, "u": 1e-6, "n": 1e-9, "p": 1e-12, "f": 1e-15}
    return float(number) * scales[suffix.lower()]


def extract(folder):
    folder = Path(folder)
    revision = folder.name.removeprefix("rev_")
    tree = parse((folder / "single_board.net").read_text(encoding="utf-8"))
    parts = {}
    for comp in children(children(tree, "components")[0], "comp"):
        ref = children(comp, "ref")[0][1]
        parts[ref] = (children(comp, "value")[0][1], {})
    for net in children(children(tree, "nets")[0], "net"):
        name = children(net, "name")[0][1]
        for node in children(net, "node"):
            parts[children(node, "ref")[0][1]][1][children(node, "pin")[0][1]] = name
    values = {line.split()[0]: line.split()[-1]
              for line in (folder / "single_board.spice.cir").read_text().splitlines()
              if line.startswith(("R", "C"))}
    adc = next(n for _, pins in parts.values() for n in pins.values() if n.endswith("/FSR_ADC"))
    powers = {"GND", "v3v3"}
    visited, selected, pending = set(), set(), [adc]
    connector = None
    while pending:
        net = pending.pop()
        if net in visited or net in powers:
            continue
        visited.add(net)
        for ref, (_, pins) in parts.items():
            if net not in pins.values():
                continue
            if ref.startswith("J"):
                connector = ref
                # Include the other terminal of this external two-wire sensor.
                pending.extend(n for p, n in pins.items() if p.isdigit())
            elif ref.startswith(("R", "C", "Q")):
                selected.add(ref)
                pending.extend(pins.values())
    pins = {p: n for p, n in parts[connector][1].items() if p.isdigit()}
    assert set(pins) == {"1", "2"}
    mapping = {"GND": "gnd", "v3v3": "v3v3", adc: "adc"}
    aliases = []
    for pin, port in (("1", "sensor_a"), ("2", "sensor_b")):
        if pins[pin] in mapping:
            aliases.append(f"Vport{pin} {port} {mapping[pins[pin]]} 0")
        else:
            mapping[pins[pin]] = port
    gate = next((n for n in visited if n.endswith("/FSR_SIG")), None)
    if gate:
        mapping[gate] = "gate"
    for net in sorted(visited - mapping.keys()):
        mapping[net] = f"n{len(mapping)}"
    lines = [f"* Source: rev_{revision}/single_board.kicad_sch; commit {revision}",
             "* kicad-cli sch export netlist --format kicadsexpr single_board.kicad_sch",
             "* kicad-cli sch export netlist --format spice single_board.kicad_sch",
             "* Generated by python -m board.extract_fsr; values below are KiCad SPICE values.",
             f"* Sensor connector: {connector}.1 sensor_a; {connector}.2 sensor_b",
             ".subckt fsr_front sensor_a sensor_b adc v3v3 gnd" + (" gate" if gate else "")]
    lines.extend(aliases)
    for ref in sorted(selected):
        value, terminals = parts[ref]
        lines.append(f"* {ref}: schematic value {value}")
        nodes = {p: mapping[n] for p, n in terminals.items()}
        if ref.startswith("Q"):
            assert value == "AO3401A"
            lines.extend([
                "* https://www.aosmd.com/sites/default/files/res/datasheets/AO3401A.pdf",
                "* Electrical Characteristics, STATIC PARAMETERS, p.2: Rds(on) max 85mOhm",
                "* at Vgs=-2.5V; Vgs(th) typical -0.9V. Assumed ideal switch; Roff=1e12.",
                f"S{ref} {nodes['2']} {nodes['3']} {nodes['2']} {nodes['1']} {ref}_AO3401A",
                f".model {ref}_AO3401A SW(Ron=0.085 Roff=1e12 Vt=0.9 Vh=0)"])
        else:
            lines.append(f"{ref} {nodes['1']} {nodes['2']} {values[ref]}")
    return "\n".join(lines + [".ends fsr_front", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("revision", choices=REVISIONS)
    args = parser.parse_args()
    rev = REVISIONS[args.revision]
    Path(__file__).with_name(f"fsr_front_{rev}.cir").write_text(
        extract(Path(os.environ["BOARD_KICAD_DIR"]) / f"rev_{rev}"), encoding="ascii")
